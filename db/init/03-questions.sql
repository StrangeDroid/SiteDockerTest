-- Test questions (in Russian), 3 per flower type, 4 answers each.
-- add_q(flowertype_id, question, correct answer, wrong 1, wrong 2, wrong 3).
-- Answers are inserted in random order because the game shows them in id order.

CREATE FUNCTION pg_temp.add_q(ft INTEGER, q TEXT, correct TEXT, w1 TEXT, w2 TEXT, w3 TEXT)
RETURNS void AS $$
DECLARE
    qid INTEGER;
BEGIN
    INSERT INTO questions (flowertype_id, content) VALUES (ft, q) RETURNING id INTO qid;
    INSERT INTO answers (question_id, content, is_correct)
    SELECT qid, a.content, a.ok
    FROM (VALUES (correct, TRUE), (w1, FALSE), (w2, FALSE), (w3, FALSE)) AS a(content, ok)
    ORDER BY random();
END;
$$ LANGUAGE plpgsql;

